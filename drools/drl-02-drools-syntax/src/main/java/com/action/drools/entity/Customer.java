package com.action.drools.entity;

/**
 * 客户（用于 Pattern 多条件演示）
 */
public class Customer {
    private int age;
    private String gender;

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public String getGender() {
        return gender;
    }

    public void setGender(String gender) {
        this.gender = gender;
    }
}
